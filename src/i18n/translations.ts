/**
 * Safely resolves either a plain string (existing Turkish prose) or a bilingual
 * { tr, en } object. Falls back gracefully to Turkish if English isn't defined yet.
 */
export function t(field: LocalizedText | undefined, lang: Language): string {
  if (!field) return '';
  if (typeof field === 'string') return field;
  return field[lang] || field.tr || field.en || '';
}

